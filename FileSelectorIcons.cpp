//
//	FileSelectorIcons::RenderFile
//

void FileSelectorIcons::RenderFile(ImDrawList* drawList, ImVec2 pos, float size, const std::string& extension) {
	static std::unordered_map<std::string, Codepoint> icons = {
		{".c", fileCode},
		{".cpp", fileCode},
		{".h", fileCode},
		{".hpp", fileCode},
		{".lua", fileCode},
		{".py", fileCode},
		{".txt", fileDocument},
		{".md", fileDocument},
		{".json", fileCog},
		{".csv", fileDelimited},
		{".jpg", fileImage},
		{".jpeg", fileImage},
		{".png", fileImage},
		{".gif", fileImage},
		{".tiff", fileImage},
		{".svg", fileChart},
		{".mp4", fileVideo},
		{".mov", fileVideo},
		{".mp3", fileMusic},
		{".aiff", fileMusic},
		{".doc", fileWord},
		{".docx", fileWord},
		{".xls", fileExcel},
		{".xlsx", fileExcel},
		{".ppt", filePowerpoint},
		{".pptx", filePowerpoint}
	};

	Codepoint codepoint = file;

	if (icons.find(extension) != icons.end()) {
		codepoint = icons[extension];
	}

	render(drawList, pos, size, codepoint);
}


//
//	FileSelectorIcons::RenderFolder
//

void FileSelectorIcons::RenderFolder(ImDrawList* drawList, ImVec2 pos, float size) {
	render(drawList, pos, size, folder);
}


//
//	FileSelectorIcons::render
//

void FileSelectorIcons::render(ImDrawList* drawList, ImVec2 pos, float size, Codepoint codepoint) {
	drawList->AddText(
		GetFont(),
		ImGui::GetStyle().FontSizeBase * size,
		pos,
		ImGui::GetColorU32(ImGuiCol_TextDisabled),
		codepoint);
}


//
//	FileSelectorIcons::GetFont
//

ImFont* FileSelectorIcons::GetFont() {
	static ImFont* font = nullptr;

	if (!font) {
		ImFontConfig config;
		std::copy_n("Icons", 6, config.Name);
		config.FontDataOwnedByAtlas = false;

		font = ImGui::GetIO().Fonts->AddFontFromMemoryTTF(
			static_cast<void*>(GetData()),
			static_cast<int>(GetSize()),
			0.0f,
			&config);
	}

	return font;
}


